"""Rebuild the fixed archive's derived records without network access.

The default command compares generated bytes with the existing files. Use
--output-dir with a new directory to save a separate regeneration.
"""
from pathlib import Path
import argparse
import csv
import hashlib
import html
import io
import json
import re
import sys
import urllib.parse

sys.dont_write_bytecode = True
from bibtex_helpers import format_pages, render_entry

ROOT = Path(__file__).resolve().parent
API_INVENTORY = json.loads((ROOT/'api_response_inventory.json').read_text())
OUTPUTS = {}

def clean(value):
    value = html.unescape(re.sub(r'<[^>]+>', '', str(value)))
    return value.replace('\u2010','-').replace('\u2011','-').replace('\u201c','"').replace('\u201d','"')

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def work(key):
    path = ROOT/'raw'/f'{key}_crossref.json'
    value = json.loads(path.read_text())['message']
    doi = value['DOI'].lower()
    return path, value, {
        'query_date':'2026-10-12',
        'provider':'Crossref',
        'request_url':next((item['request_url'] for item in API_INVENTORY if item['key']==key and item['provider']=='crossref'), 'https://api.crossref.org/works/'+urllib.parse.quote(doi,safe='')),
        'response_http_status':200,
        'response_payload_sha256':digest(path),
        'response_payload_file':'raw/'+path.name,
        'doi':doi,
        'title':value.get('title',[None])[0],
        'authors':value.get('author'),
        'container_title':value.get('container-title',[None])[0],
        'published':value.get('published'),
        'published_print':value.get('published-print'),
        'published_online':value.get('published-online'),
        'volume':value.get('volume'),
        'issue':value.get('issue'),
        'pages':value.get('page'),
        'record_type':value.get('type'),
        'doi_url':'https://doi.org/'+doi,
        'publisher_record_url':value.get('URL'),
        'fulltext_links':value.get('link',[]),
    }

definitions = {
    'price1965networks': ('10.1126/science.149.3683.510','Networks of Scientific Papers',1965,
        'Historical basis for citation immediacy and research fronts. The exact age-at-most-five statistic is defined by the present study.'),
    'burton1960halflife': ('10.1002/asi.5090110105','The "half-life" of some scientific and technical literatures',1960,
        'Historical treatment of literature ageing. It does not identify reference retention across IPCC assessments.'),
    'bradford1985sources': ('10.1177/016555158501000407','Sources of information on specific subjects 1934',1985,
        'DOI-registered 1985 reprint. The DOI and pages refer to the reprint, not to the 1934 Engineering publication.'),
    'hill1973diversity': ('10.2307/1934352','Diversity and Evenness: A Unifying Notation and Its Consequences',1973,
        'Primary effective-number framework for comparing richness, entropy diversity and concentration diversity.'),
    'simpson1949diversity': ('10.1038/163688a0','Measurement of Diversity',1949,
        'Primary concentration/diversity measure based on category abundances.'),
    'jost2006entropy': ('10.1111/j.2006.0030-1299.14714.x','Entropy and diversity',2006,
        'Explains conversion of entropy and concentration indices to effective numbers.'),
}
records=[]
bib=[]
for key,(expected_doi,expected_title,expected_year,reason) in definitions.items():
    path,raw,record=work(key)
    assert record['doi']==expected_doi
    assert clean(record['title']).casefold()==clean(expected_title).casefold()
    assert raw['published']['date-parts'][0][0]==expected_year
    authors=raw.get('author')
    enrichment=None
    if key=='bradford1985sources':
        _,author_source,author_record=work('bradford1976sources')
        authors=author_source['author']
        assert authors[0]['family']=='Bradford' and authors[0]['given']=='S. C.'
        _,companion,companion_record=work('brookes1985bradford')
        assert 'by S.C. Bradford' in companion['title'][0]
        enrichment={
            'field':'author','value':'Bradford, S. C.',
            'reason':'The 1985 Crossref record omits authors. A DOI-registered 1976 reprint supplies S. C. Bradford, and the publisher companion introduction explicitly credits the work to S.C. Bradford.',
            'primary_supporting_records':[author_record,companion_record],
            'publisher_support_url':'https://journals.sagepub.com/doi/10.1177/016555158501000406',
        }
    author_names=[]
    for author in authors:
        family=author['family']
        if family.isupper():family=family.title()
        author_names.append(f"{family}, {author.get('given','')}".rstrip(', '))
    fields={
        'author':' and '.join(author_names),
        'title':clean(record['title']),
        'journal':record['container_title'],
        'year':str(expected_year),'volume':str(record['volume']),
        'number':str(record['issue']),'pages':format_pages(record['pages']),
        'doi':record['doi'],'url':record['doi_url'],
    }
    if key=='bradford1985sources':fields['note']='Reprint of the paper originally published in 1934'
    record.update({'candidate_key':key,'decision':'accepted','included_in_bib':True,
                   'decision_reason':reason,'title_checked_against':expected_title,
                   'year_checked_against':expected_year,'bibtex_fields':fields,
                   'author_enrichment':enrichment,
                   'source_reading_level':'Relevant original full-text passages' if key=='price1965networks' else 'Publisher abstract and metadata' if key in ['burton1960halflife','hill1973diversity','jost2006entropy'] else 'Metadata and primary supporting records'})
    bib.append(render_entry('article',key,fields))
    records.append(record)

for key,reason in [
    ('bradford1976sources','A second DOI-registered reprint with complete author metadata. It corroborates the 1985 author attribution and is omitted as a redundant edition.'),
    ('brookes1985bradford','Primary publisher companion introduction supplies Bradford attribution. Its pages 173-175 are separate from the Bradford reprint pages 176-180.'),
]:
    _,_,record=work(key)
    record.update({'candidate_key':key,'decision':'accepted_supporting_record','included_in_bib':False,'decision_reason':reason,'source_reading_level':'Metadata'})
    records.append(record)

for key,title,reason in [
    ('price1970citationmeasures','Citation Measures of Hard Science, Soft Science, Technology, and Nonscience','No exact DOI/title record was found in the archived Crossref title and author queries. OpenAlex requests were rate limited. No DOI was invented and no BibTeX entry was added.'),
    ('bradford1934original','Sources of information on specific subjects','No original-1934 DOI/title record was verified. DOI 10.1177/016555158501000407 identifies a 1985 reprint; attaching it to an Engineering 1934 entry would misidentify the edition.'),
]:
    records.append({'candidate_key':key,'query_date':'2026-10-12','candidate_title':title,
                    'decision':'rejected_for_bib','included_in_bib':False,'doi':None,
                    'decision_reason':reason})

OUTPUTS['references_additions.bib'] = ('\n\n'.join(bib)+'\n').encode('utf-8')
inventory=json.loads((ROOT/'api_response_inventory.json').read_text())
search_queries={
    'price1970citationmeasures_crossref_search.json':{'query.bibliographic':'Citation measures of hard science soft science technology and nonscience','rows':5},
    'price1970title_author_crossref_search.json':{'query.title':'Citation measures of hard science soft science technology and nonscience','query.author':'Price','rows':8},
    'bradford1934title_author_crossref_search.json':{'query.title':'Sources of information on specific subjects','query.author':'Bradford','rows':8},
}
search_records=[]
for name,params in search_queries.items():
    path=ROOT/'raw'/name
    data=json.loads(path.read_text())
    search_records.append({'provider':'Crossref','query_date':'2026-10-12',
        'request_url':'https://api.crossref.org/works?'+urllib.parse.urlencode(params),
        'response_payload_sha256':digest(path),'response_payload_file':'raw/'+name,
        'returned_records':[{'doi':item.get('DOI'),'title':item.get('title'),'author':item.get('author'),'published':item.get('published')} for item in data['message']['items']]})
verification={
    'query_date':'2026-10-12','purpose':'Verify classic bibliometric citation candidates for an assessment-reference analysis',
    'acceptance_rule':'Every included reference has an exact DOI and normalized title match in a successful Crossref API work record, plus matching year and bibliographic fields. Author gaps receive documented primary-source enrichment.',
    'title_normalization':'Remove HTML formatting, normalize curly quotation marks and Unicode hyphens to ASCII; retain words, title suffixes and publication year.',
    'candidates':records,'search_records':search_records,
    'provider_failures':[record for record in inventory if 'error' in record],
    'accepted_bibtex_keys':list(definitions),
    'bibliography_sha256':hashlib.sha256(OUTPUTS['references_additions.bib']).hexdigest(),
    'private_manuscript_or_full_bibliography_exported':False,
    'Price_definition_check':{
        'primary_source_url':'https://garfield.library.upenn.edu/papers/pricenetworks1965.pdf',
        'source_pages':'513-514 (PDF pages 4-5)',
        'finding':'The paper examines an immediacy distribution. It describes a recent-reference band from one to six years. The exact integer-age-at-most-five fraction used in the assessment analysis is a study-defined recency summary.',
        'recommended_term':'recent-reference share; alternatively explicitly defined Price-style recent-reference fraction',
        'canonical_Price_index_claim_supported':False,
        'Price_1970_fulltext_verified':False,
    },
}
OUTPUTS['reference_verification.json'] = (json.dumps(verification,indent=2,ensure_ascii=False)+'\n').encode('utf-8')
columns=['query_date','candidate_key','decision','included_in_bib','doi','title','year','authors','journal','volume','issue','pages','provider','request_url','response_payload_sha256','decision_reason']
with io.StringIO(newline='') as handle:
    writer=csv.DictWriter(handle,fieldnames=columns);writer.writeheader()
    for record in records:
        fields=record.get('bibtex_fields',{})
        writer.writerow({
            'query_date':record['query_date'],'candidate_key':record['candidate_key'],
            'decision':record['decision'],'included_in_bib':record['included_in_bib'],
            'doi':record.get('doi'),'title':clean(record.get('title',record.get('candidate_title',''))),
            'year':fields.get('year',record.get('published',{}).get('date-parts',[['']])[0][0]),
            'authors':fields.get('author',json.dumps(record.get('authors'),ensure_ascii=False)),
            'journal':record.get('container_title'),'volume':record.get('volume'),
            'issue':record.get('issue'),'pages':record.get('pages'),
            'provider':record.get('provider'),'request_url':record.get('request_url'),
            'response_payload_sha256':record.get('response_payload_sha256'),
            'decision_reason':record['decision_reason'],
        })
    OUTPUTS['reference_verification.csv'] = handle.getvalue().encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path,
                        help='Write derived records to a new directory. The fixed archive remains unchanged.')
    args = parser.parse_args()
    if args.output_dir is None:
        mismatches = [name for name, payload in OUTPUTS.items()
                      if (ROOT/name).read_bytes() != payload]
        result = {'mode':'offline_byte_check', 'files_checked':len(OUTPUTS),
                  'mismatches':mismatches, 'passed':not mismatches}
    else:
        destination = args.output_dir.resolve()
        if destination == ROOT or ROOT in destination.parents:
            parser.error('The output directory must be outside the fixed archive.')
        try:
            destination.mkdir(parents=True, exist_ok=False)
        except FileExistsError:
            parser.error('The output directory already exists; choose a new directory.')
        for name, payload in OUTPUTS.items():
            (destination/name).write_bytes(payload)
        result = {'mode':'offline_regeneration', 'output_dir':str(destination),
                  'files_written':len(OUTPUTS), 'passed':True,
                  'raw_payload_source':str(ROOT/'raw')}
    result.update({'included_reference_keys':list(definitions), 'records':len(records),
                   'bibliography_sha256':verification['bibliography_sha256']})
    print(json.dumps(result, indent=2))
    return 0 if result['passed'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
